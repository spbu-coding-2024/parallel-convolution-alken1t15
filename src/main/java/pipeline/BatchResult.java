package pipeline;

/**
 * Результат batch-обработки изображений.
 *
 * Хранит количество обработанных файлов и время,
 * затраченное на разные этапы pipeline:
 * чтение, применение фильтра и запись результата.
 */
public record BatchResult(
        // Количество успешно обработанных и сохранённых файлов.
        int files,

        // Общее время выполнения всей batch-обработки в наносекундах.
        long totalNanos,

        // Суммарное время, потраченное на чтение изображений.
        long readNanos,

        // Суммарное время, потраченное на применение фильтра.
        long convolutionNanos,

        // Суммарное время, потраченное на сохранение обработанных изображений.
        long writeNanos
) {

    /**
     * Возвращает общее время выполнения в миллисекундах.
     *
     * Так как System.nanoTime() измеряет время в наносекундах,
     * делим значение на 1_000_000.0.
     *
     * @return общее время обработки в миллисекундах
     */
    public double totalMillis() {
        return totalNanos / 1_000_000.0;
    }

    /**
     * Возвращает среднее время обработки одного файла.
     *
     * Если файлов не было, возвращаем 0.0,
     * чтобы избежать деления на ноль.
     *
     * @return среднее время обработки одного файла в миллисекундах
     */
    public double averageMillisPerFile() {
        return files == 0 ? 0.0 : totalMillis() / files;
    }
}
